// CodeBridges POS Offline-First Service Worker
const CACHE_NAME = 'codebridge-pos-v1';
const STATIC_ASSETS = [
  '/',
  '/pos/pos-terminal',
  '/pos/customer-display',
  '/pos/kitchen-display',
  '/manifest.json',
  '/logo/Codebridge.svg',
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => {
      return cache.addAll(STATIC_ASSETS).catch((err) => {
        console.warn('Pre-cache asset warning:', err);
      });
    })
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => {
      return Promise.all(
        keys.map((key) => {
          if (key !== CACHE_NAME) {
            return caches.delete(key);
          }
        })
      );
    })
  );
  self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  // Do not intercept non-GET or cross-origin API requests (handled by IndexedDB offlineSync engine)
  if (event.request.method !== 'GET') return;
  const url = new URL(event.request.url);
  if (url.pathname.startsWith('/api/')) return;

  event.respondWith(
    caches.match(event.request).then((cachedResponse) => {
      if (cachedResponse) {
        // Return cached and refresh in background
        fetch(event.request)
          .then((networkResponse) => {
            if (networkResponse && networkResponse.status === 200) {
              caches.open(CACHE_NAME).then((cache) => cache.put(event.request, networkResponse));
            }
          })
          .catch(() => {});
        return cachedResponse;
      }

      return fetch(event.request).catch(() => {
        // If offline and request is an HTML page navigation, fallback to cached pos-terminal
        if (event.request.mode === 'navigate') {
          return caches.match('/pos/pos-terminal');
        }
      });
    })
  );
});
